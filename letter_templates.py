def render_template(category: str, name: str, city: str,
                    phone: str = "", address: str = "") -> dict:
    """Заполняет шаблон данными лида."""
    cat = category.lower().replace(" ", "_")
    # Маппинг OSM категорий → ключи шаблонов
    cat_map = {
        "cafe": "cafe", "restaurant": "restaurant", "fast_food": "fast_food",
        "bar": "bar", "pub": "bar",
        "shop": "shop",
        "beauty": "beauty", "hairdresser": "beauty",
        "car_service": "car_service", "car_wash": "car_service",
        "hotel": "hotel", "hostel": "hotel", "guest_house": "hotel",
        "clothes": "clothing", "boutique": "clothing", "clothing": "clothing",
    }

    template_key = cat_map.get(cat, "other")
    template = TEMPLATES.get(template_key, TEMPLATES["other"])

    subject = template["subject"].format(name=name, city=city)
    body = template["body"].format(name=name, city=city, phone=phone)

    return {
        "category": cat,
        "template_key": template_key,
        "emoji": template["emoji"],
        "subject": subject,
        "body": body,
    }


def list_templates():
    """Выводит список всех доступных шаблонов."""
    print("📋 Доступные шаблоны писем:")
    print("=" * 60)
    for key, tmpl in TEMPLATES.items():
        print(f"\n{tmpl['emoji']} {key}")
        print(f"   Тема: {tmpl['subject'].format(name='[Название]', city='[Город]')}")
        preview = tmpl['body'].format(name='[Название]', city='[Город]', phone='')
        preview = preview[:120].replace('\n', ' ') + "..."
        print(f"   {preview}")


def main():
    parser = argparse.ArgumentParser(description="Шаблоны писем для лидов")
    parser.add_argument("--category", "-c", help="Категория бизнеса")
    parser.add_argument("--name", "-n", help="Название бизнеса")
    parser.add_argument("--city", help="Город")
    parser.add_argument("--phone", "-p", default="", help="Телефон")
    parser.add_argument("--list", "-l", action="store_true", help="Список шаблонов")
    parser.add_argument("--json", action="store_true", help="Вывод в JSON")
    args = parser.parse_args()

    if args.list:
        list_templates()
        return

    if not all([args.category, args.name, args.city]):
        print("Укажи --category, --name, --city (или --list)")
        return

    result = render_template(args.category, args.name, args.city, args.phone)

    if args.json:
        print(json.dumps(result, ensure_ascii=False, indent=2))
    else:
        print(f"\n{'='*60}")
        print(f"{result['emoji']} ШАБЛОН: {result['template_key']}")
        print(f"{'='*60}")
        print(f"\n📧 ТЕМА:")
        print(f"   {result['subject']}")
        print(f"\n📝 ТЕЛО ПИСЬМА:")
        print(f"{result['body']}")
        print(f"\n{'='*60}")


if __name__ == "__main__":
    main()
